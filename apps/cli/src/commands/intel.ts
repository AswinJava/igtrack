function claimFlagText(claim: ClaimView): string {
  const flags: string[] = [];
  if (claim.conflicted) flags.push("conflicted");
  if (claim.dueForReview) flags.push("due for review");
  if (claim.status === "RETRACTED") flags.push("retracted");
  return flags.length === 0 ? "-" : flags.join(" · ");
}

function renderClaimGroups(groups: ClaimGroupView[], sections: string[]): void {
  if (groups.length === 0) {
    sections.push("  No active claims recorded.");
    return;
  }
  for (const group of groups) {
    sections.push(
      "",
      `${group.predicate}  [${group.relation}]${
        group.sourceDomains.length > 0 ? `  sources: ${group.sourceDomains.join(", ")}` : ""
      }`,
      table(
        ["value", "kind", "source", "basis date", "age", "flags"],
        group.claims.map((claim) => [
          claim.value,
          claim.sourceKind,
          claim.sourceUrl ?? "operator assertion",
          (claim.retrievedAt ?? claim.recordedAt).slice(0, 10),
          `${claim.ageDays}d`,
          claimFlagText(claim),
        ]),
      ),
    );
  }
  sections.push("  (excerpts, hashes and stated times are in --json)");
}

function mdCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

function mdTable(headers: readonly string[], rows: readonly (readonly string[])[]): string[] {
  if (rows.length === 0) return ["(none)"];
  const lines = [`| ${headers.join(" | ")} |`, `| ${headers.map(() => "---").join(" | ")} |`];
  for (const row of rows) {
    lines.push(`| ${row.map((cell) => mdCell(cell)).join(" | ")} |`);
  }
  return lines;
}

function themesMarkdown(result: ResearchResult): string[] {
  const lines = ["## Themes (derived from stored captions — corpus stated)", ""];
  if (result.themes.state === "UNAVAILABLE") {
    lines.push(`UNAVAILABLE — ${display(result.themes.reason)}`);
  } else {
    lines.push(
      `- terms: ${result.themes.terms.length === 0 ? "(none)" : result.themes.terms.map((t) => `${t.term} (${t.count})`).join(" · ")}`,
      `- hashtags: ${result.themes.hashtags.length === 0 ? "(none)" : result.themes.hashtags.map((t) => `#${t.term} (${t.count})`).join(" · ")}`,
    );
  }
  lines.push("", result.themes.note);
  return lines;
}

function cadenceMarkdown(result: ResearchResult): string[] {
  const lines = ["## Cadence (derived from stored publish timestamps — formula stated)", ""];
  lines.push(
    result.cadence.state === "UNAVAILABLE"
      ? `UNAVAILABLE — ${display(result.cadence.reason)}`
      : `first ${display(result.cadence.firstPublishedAt)} · last ${display(result.cadence.lastPublishedAt)} · median gap ${result.cadence.medianGapDays === null ? "unavailable" : `${result.cadence.medianGapDays} days`} · ${result.cadence.timestampRows} distinct timestamp(s)`,
  );
  lines.push("", result.cadence.note);
  return lines;
}

function audienceMarkdown(result: ResearchResult): string[] {
  const lines = ["## Audience (platform-reported insights; absences surfaced)", ""];
  if (result.audience.state === "UNAVAILABLE") {
    lines.push(`UNAVAILABLE — ${display(result.audience.reason)}`);
  } else {
    lines.push(
      ...mdTable(
        ["metric", "period", "dimension", "value", "ends"],
        result.audience.latest.map((point) => [
          point.metric,
          point.period,
          display(point.dimensionValue ?? point.dimension),
          String(point.value),
          display(point.endTime === null ? null : point.endTime.slice(0, 10)),
        ]),
      ),
    );
    for (const absence of result.audience.latestAbsences) {
      lines.push(`- ABSENT ${absence.metric} ${absence.period}: ${absence.reason}`);
    }
  }
  lines.push("", result.audience.note);
  return lines;
}

function changesMarkdown(result: ResearchResult): string[] {
  const lines = [`## Recent changes (recorded events, last ${result.changes.windowDays} days)`, ""];
  if (result.changes.state === "UNAVAILABLE") {
    lines.push(`UNAVAILABLE — ${display(result.changes.reason)}`);
  } else {
    const row = (label: string, v: { count: number; latestAt: string | null } | null): string[] => [
      label,
      v === null ? "unavailable" : String(v.count),
      v === null || v.latestAt === null ? "unavailable" : v.latestAt.slice(0, 10),
    ];
    lines.push(
      ...mdTable(
        ["kind", "recorded", "latest"],
        [
          row("profile changes", result.changes.profileChanges),
          row("post changes", result.changes.postChanges),
          row("follow deltas", result.changes.followDeltas),
        ],
      ),
    );
  }
  lines.push("", result.changes.note);
  return lines;
}

/** The same report as a Markdown hand-off document (igtrack research --format md). */
function researchMarkdown(result: ResearchResult): string {
  const lines: string[] = [
    `# Research report — @${result.target.username}`,
    "",
    `Generated ${result.computedAt} · mode ${result.target.observationMode} · status ${result.target.status} · local name ${display(result.target.localName)} · tags ${display(result.target.tags)}`,
    "",
    "## Identity",
    `- platform id: ${display(result.identity.account.igId)}`,
    `- account type: ${display(result.identity.account.accountType)} · private ${display(result.identity.account.isPrivate)} · verified ${display(result.identity.account.isVerified)}`,
    `- route: ${result.identity.route.providerMethod} — ${result.identity.route.scope}`,
    "",
    "## Platform observations",
    "",
    ...mdTable(
      ["field", "value"],
      [
        ["followers (latest snapshot)", display(result.platform.profile.latest?.followerCount ?? null)],
        ["following (latest snapshot)", display(result.platform.profile.latest?.followingCount ?? null)],
        ["posts (latest snapshot)", display(result.platform.profile.latest?.postCount ?? null)],
        ["profile snapshots", String(result.platform.profile.snapshotCount)],
        ["stored media rows", display(result.platform.media?.storedCount ?? null)],
      ],
    ),
    "",
    result.platform.media === null
      ? "No media rows are stored; the coverage table below names what a scan could record."
      : result.platform.media.bounded === true
        ? "Media rows are a BOUNDED, non-pageable preview (Business Discovery): never \"the account's posts\"; published time and first-observed time are different facts."
        : "Media rows are first observations; a row absent from a later listing is never reported as removed.",
    "",
    ...themesMarkdown(result),
    "",
    ...cadenceMarkdown(result),
    "",
    ...audienceMarkdown(result),
    "",
    ...changesMarkdown(result),
    "",
    "## Claims (operator/agent-submitted — not observations)",
    "",
    result.claims.statement,
    ...(result.claims.since === null
      ? []
      : [
          "",
          `> \`--since ${result.claims.since}\`: ${result.claims.omittedBefore} older claim row(s) omitted from this view (still stored; nothing deleted).`,
        ]),
  ];
  for (const group of result.claims.groups) {
    lines.push(
      "",
      `### ${group.predicate} [${group.relation}]`,
      "",
      ...(group.sourceDomains.length > 0 ? [`Sources: ${group.sourceDomains.join(", ")}`, ""] : []),
      ...mdTable(
        ["value", "kind", "source", "basis date", "flags"],
        group.claims.map((claim) => [
          claim.value,
          claim.sourceKind,
          claim.sourceUrl ?? "operator assertion",
          (claim.retrievedAt ?? claim.recordedAt).slice(0, 10),
          claimFlagText(claim),
        ]),
      ),
    );
  }
  if (result.claims.retracted.length > 0) {
    lines.push(
      "",
      `### Retracted (${result.claims.totals.retracted}, never deleted)`,
      "",
      ...mdTable(
        ["value", "predicate", "retracted at", "reason"],
        result.claims.retracted.map((claim) => [
          claim.value,
          claim.predicate,
          display(claim.retractedAt === null ? null : claim.retractedAt.slice(0, 10)),
          display(claim.retractionReason),
        ]),
      ),
    );
  }

  lines.push("", "## Contradictions", "");
  if (result.contradictions.length === 0) {
    lines.push("None: no predicate has conflicting active values.");
  } else {
    for (const contradiction of result.contradictions) {
      lines.push(`- **${contradiction.predicate}**`);
      for (const value of contradiction.values) {
        lines.push(`  - "${mdCell(value.value)}" ← ${value.sources.map(mdCell).join(" ; ")}`);
      }
    }
  }

  lines.push("", "## Leads (stored signal rows - not claims, not researched)", "");
  if (result.leads.state === "UNAVAILABLE") {
    lines.push(`UNAVAILABLE - ${display(result.leads.reason)}`);
  } else {
    lines.push(...mdTable(["account", "signals"], result.leads.items.map((lead) => [lead.username, lead.signals.join(" · ")])));
    if (result.leads.syntheticItems.length > 0) {
      lines.push(
        "",
        "Synthetic leads (fixture data - evidence about the fixture, never about a person):",
        "",
        ...mdTable(["account", "signals"], result.leads.syntheticItems.map((lead) => [lead.username, lead.signals.join(" · ")])),
      );
    }
  }
  lines.push("", result.leads.note);

  lines.push("", "## Connections (evidence-ranked; counts of stored rows, never affinity)", "");
  if (result.connections.state === "UNAVAILABLE") {
    lines.push(`UNAVAILABLE - ${display(result.connections.reason)}`);
  } else {
    lines.push(
      ...mdTable(
        ["account", "mentions", "comments", "deltas"],
        result.connections.ranks.map((rank) => [
          rank.username,
          String(rank.signals.mentions),
          String(rank.signals.comments),
          String(rank.signals.deltas),
        ]),
      ),
    );
    if (result.connections.syntheticRanks.length > 0) {
      lines.push(
        "",
        "Synthetic connections (fixture data - never evidence about a person):",
        "",
        ...mdTable(
          ["account", "mentions", "comments", "deltas"],
          result.connections.syntheticRanks.map((rank) => [
            rank.username,
            String(rank.signals.mentions),
            String(rank.signals.comments),
            String(rank.signals.deltas),
          ]),
        ),
      );
    }
    if (result.connections.truncated) {
      lines.push("", "Note: more ranked accounts are stored than this list shows.");
    }
  }

  lines.push("", "## Research runs (autonomous public-web acquisition)", "");
  if (result.researchRuns.state === "UNAVAILABLE") {
    lines.push(`${display(result.researchRuns.reason)}`, "", result.researchRuns.note);
  } else {
    lines.push(
      ...mdTable(
        ["run", "question", "focus", "status", "docs fetched/planned", "failed", "candidates", "stored", "duplicate", "refused", "started"],
        result.researchRuns.runs.map((run) => [
          run.id.slice(0, 8),
          run.question,
          run.focusIntent,
          run.status,
          `${run.documentsFetched}/${run.documentsPlanned}`,
          String(run.documentsFailed),
          String(run.candidatesFound),
          String(run.claimsStored),
          String(run.claimsDuplicate),
          String(run.claimsRefused),
          run.startedAt.slice(0, 10),
        ]),
      ),
      "",
      result.researchRuns.note,
    );
    for (const run of result.researchRuns.runs) {
      if (run.searchUnavailableReason !== null) {
        lines.push("", `Run ${run.id.slice(0, 8)}: search UNAVAILABLE — ${run.searchUnavailableReason}`);
      }
    }
  }

  lines.push(
    "",
    "## Coverage",
    "",
    ...mdTable(
      ["capability", "state", "rows", "reason"],
      result.coverage.map((row) => [
        row.label,
        row.state,
        row.observedRows === null ? "no writer" : String(row.observedRows),
        row.reason ?? "-",
      ]),
    ),
    "",
    "## Notes",
    ...result.notes.map((note) => `- ${note}`),
  );
  return lines.join("\n");
}

export async function runClaims(args: ParsedArgs): Promise<number> {
  const json = isJson(args.flags);
  const sub = args.positionals[0];
  if (sub === undefined) {
    throw new UsageError("Usage: igtrack claims <list|add|retract> ...  (igtrack claims --help)");
  }
  const ctx = await createContext();
  try {
    if (sub === "list") {
      const target = args.positionals[1];
      if (target === undefined) {
        throw new UsageError("Usage: igtrack claims list <target id|username>");
      }
      const result = await opClaimList(ctx, {
        target,
        predicate: flagString(args.flags, "predicate"),
        includeRetracted: flagBool(args.flags, "include-retracted"),
      });
      const sections: string[] = [
        `Claims    @${result.target.username}  (${result.totals.active} active · ${result.totals.retracted} retracted · ${result.totals.predicates} predicate(s))`,
      ];
      renderClaimGroups(result.groups, sections);
      if (result.retracted.length > 0) {
        sections.push(
          "",
          "Retracted (kept readable; excluded from relation labels):",
          table(
            ["value", "predicate", "retracted at", "reason"],
            result.retracted.map((claim) => [
              claim.value,
              claim.predicate,
              display(claim.retractedAt === null ? null : claim.retractedAt.slice(0, 10)),
              display(claim.retractionReason),
            ]),
          ),
        );
      }
      if (result.note !== null) sections.push("", result.note);
      emit({ json, meta: ctx.meta, data: result, human: sections.join("\n") });
      return 0;
    }

    if (sub === "add") {
      const target = args.positionals[1];
      if (target === undefined) {
        throw new UsageError("Usage: igtrack claims add <target> --predicate P --value V [--source-url URL]");
      }
      const predicate = flagString(args.flags, "predicate");
      const value = flagString(args.flags, "value");
      if (predicate === undefined || value === undefined) {
        throw new UsageError("claims add requires --predicate and --value.");
      }
      const sourceUrl = flagString(args.flags, "source-url");
      const sourceTitle = flagString(args.flags, "source-title");
      const excerpt = flagString(args.flags, "excerpt");
      const statedAt = flagString(args.flags, "stated-at");
      const retrievedAt = flagString(args.flags, "retrieved-at");
      const result = await opClaimAdd(ctx, {
        target,
        predicate,
        value,
        ...(sourceUrl !== undefined ? { sourceUrl } : {}),
        ...(sourceTitle !== undefined ? { sourceTitle } : {}),
        ...(excerpt !== undefined ? { excerpt } : {}),
        ...(statedAt !== undefined ? { statedAt } : {}),
        ...(retrievedAt !== undefined ? { retrievedAt } : {}),
      });
      const claim = result.claim;
      const human = [
        `Claim     ${claim.id}`,
        `Target    @${result.target.username}  (${result.target.status})`,
        `Predicate ${claim.predicate}  [${display(claim.relation)}]`,
        `Value     ${claim.value}`,
        `Source    ${claim.sourceKind}${claim.sourceUrl === null ? "" : ` — ${claim.sourceUrl}`}`,
        claim.sourceDomain === null ? null : `Domain    ${claim.sourceDomain}`,
        claim.excerptHash === null ? null : `Excerpt   sha256 ${claim.excerptHash.slice(0, 16)}…`,
        "",
        result.note,
      ]
        .filter((line) => line !== null)
        .join("\n");
      emit({ json, meta: ctx.meta, data: result, human });
      return 0;
    }

    if (sub === "retract") {
      const claimId = args.positionals[1];
      if (claimId === undefined) {
        throw new UsageError("Usage: igtrack claims retract <claimId> --reason TEXT --yes");
      }
      const reason = flagString(args.flags, "reason");
      if (reason === undefined) throw new UsageError("claims retract requires --reason.");
      const result = await opClaimRetract(ctx, {
        claimId,
        reason,
        confirm: flagBool(args.flags, "yes"),
      });
      const human = [
        `Claim     ${result.claim.id}`,
        `Status    ${result.claim.status} at ${display(result.claim.retractedAt)}`,
        `Reason    ${display(result.claim.retractionReason)}`,
        "",
        result.note,
      ].join("\n");
      emit({ json, meta: ctx.meta, data: result, human });
      return 0;
    }

    throw new UsageError(`Unknown claims subcommand "${sub}". Use list, add or retract.`);
  } finally {
    await ctx.close();
  }
}

export async function runResearch(args: ParsedArgs): Promise<number> {
  const json = isJson(args.flags);
  const target = args.positionals[0];
  if (target === undefined) {
    throw new UsageError("Usage: igtrack research <target id|username>");
  }
  const connectionLimit = flagNumber(args.flags, "connections", 10);
  const format = (flagString(args.flags, "format") ?? "text").toLowerCase();
  if (format !== "text" && format !== "md" && format !== "markdown") {
    throw new UsageError(`Unknown --format "${format}". Use text (default) or md.`);
  }
  if (json && format !== "text") {
    throw new UsageError(
      "--json and --format are mutually exclusive: --json emits the machine envelope, --format md the hand-off document.",
    );
  }
  const since = flagString(args.flags, "since");
  const runMode = flagBool(args.flags, "run");
  const ctx = await createContext();
  try {
    if (runMode) {
      // The acquisition path: fetch named/public sources through the
      // gate, extract, validate, store. It writes claims + a run record —
      // the ONLY research flag that writes.
      const question = flagString(args.flags, "question");
      if (question === undefined || question.trim() === "") {
        throw new UsageError(
          "--run needs --question \"What are we trying to find out about this account?\"",
        );
      }
      if (format !== "text") {
        throw new UsageError(
          "--run prints the acquisition summary as text (or --json for the machine envelope); run the report separately with --format md.",
        );
      }
      const urlFlag = flagString(args.flags, "url");
      const urls =
        urlFlag === undefined
          ? []
          : urlFlag
              .split(",")
              .map((u) => u.trim())
              .filter((u) => u !== "");
      const maxSources =
        args.flags["max-sources"] === undefined
          ? undefined
          : flagNumber(args.flags, "max-sources", 10);
      const refresh = flagBool(args.flags, "refresh");
      const runResult = await opResearchRun(ctx, {
        target,
        question,
        ...(urls.length > 0 ? { urls } : {}),
        ...(maxSources !== undefined ? { maxSources } : {}),
        ...(refresh ? { refresh: true } : {}),
      });
      const runSections: string[] = [
        `Research run ${runResult.runId}  @${runResult.target.username}  ${runResult.status}`,
        "",
        `Question   ${runResult.question}`,
        `Focus      ${runResult.focus.intent} — ${runResult.focus.rationale}`,
        `Bounds     ${runResult.bounds.enforced}`,
        `Search     provider ${display(runResult.search.provider)} · ${runResult.search.queries.length} query(ies) · ${runResult.search.candidateUrls} candidate URL(s)`,
      ];
      if (runResult.search.unavailableReason !== null) {
        runSections.push(`           UNAVAILABLE — ${runResult.search.unavailableReason}`);
      }
      runSections.push(
        "",
        "Documents",
        table(
          ["outcome", "url", "title", "detail"],
          runResult.documents.map((doc) => [
            doc.outcome,
            doc.url,
            display(doc.title),
            [
              doc.httpStatus === null ? null : `HTTP ${doc.httpStatus}`,
              doc.byteSize === null ? null : `${doc.byteSize} B`,
              `${doc.candidatesFound} candidate(s)`,
              doc.outcomeReason,
            ]
              .filter((part): part is string => part !== null)
              .join(" · "),
          ]),
        ),
        "",
        "Totals",
        `  planned ${runResult.totals.planned} · fetched ${runResult.totals.fetched} · reused ${runResult.totals.reused} · failed ${runResult.totals.failed}`,
        `  candidates ${runResult.totals.candidates} · claims stored ${runResult.totals.claimsStored} · duplicates refused ${runResult.totals.claimsDuplicate} · predicate refusals ${runResult.totals.claimsRefused}`,
      );
      if (runResult.claims.length > 0) {
        runSections.push(
          "",
          "Claims stored (each with source URL, excerpt and SHA-256; visible in the next report)",
          table(
            ["predicate", "value", "source"],
            runResult.claims.map((claim) => [
              claim.predicate,
              claim.value,
              display(claim.sourceUrl),
            ]),
          ),
        );
      }
      runSections.push("", "Notes:", ...runResult.notes.map((note) => `  · ${note}`));
      emit({
        json,
        meta: ctx.meta,
        data: runResult,
        human: runSections.join("\n"),
      });
      return runResult.status === "FAILED" ? 1 : 0;
    }
    const result = await opResearch(ctx, {
      target,
      connectionLimit,
      ...(since !== undefined ? { since } : {}),
    });
    const sections: string[] = [
      `Research  @${result.target.username}  (${result.target.observationMode} · ${result.target.status})  computed ${result.computedAt}`,
      "",
      "Identity",
      `  platform id ${display(result.identity.account.igId)} · type ${display(result.identity.account.accountType)} · private ${display(result.identity.account.isPrivate)} · verified ${display(result.identity.account.isVerified)}`,
      `  route ${result.identity.route.providerMethod} — ${result.identity.route.scope}`,
      `  local name ${display(result.target.localName)} · tags ${display(result.target.tags)}`,
      "",
      "Platform observations (recorded rows only; never merged with claims)",
      table(
        ["field", "value"],
        [
          ["followers (latest snapshot)", display(result.platform.profile.latest?.followerCount ?? null)],
          ["following (latest snapshot)", display(result.platform.profile.latest?.followingCount ?? null)],
          ["posts (latest snapshot)", display(result.platform.profile.latest?.postCount ?? null)],
          ["profile snapshots", String(result.platform.profile.snapshotCount)],
          ["stored media rows", display(result.platform.media?.storedCount ?? null)],
        ],
      ),
      result.platform.media === null
        ? "  No media rows are stored; what a scan could record is described per capability below."
        : result.platform.media.bounded === true
          ? "  Media rows are a BOUNDED, non-pageable preview (Business Discovery): never \"the account's posts\"; each row's published time and first-observed time are different facts."
          : "  Media rows are first observations; a row absent from a later listing is never reported as removed.",
    ];

    sections.push("", `Themes (derived; corpus stated — ${result.themes.captionRows} caption(s) with text)`);
    if (result.themes.state === "UNAVAILABLE") {
      sections.push(`  UNAVAILABLE — ${display(result.themes.reason)}`);
    } else {
      sections.push(
        `  Terms     ${result.themes.terms.length === 0 ? "(none)" : result.themes.terms.map((t) => `${t.term} (${t.count})`).join(" · ")}`,
        `  Hashtags  ${result.themes.hashtags.length === 0 ? "(none)" : result.themes.hashtags.map((t) => `#${t.term} (${t.count})`).join(" · ")}`,
      );
    }
    sections.push(`  ${result.themes.note}`);

    sections.push("", "Cadence (derived; formula stated)");
    if (result.cadence.state === "UNAVAILABLE") {
      sections.push(`  UNAVAILABLE — ${display(result.cadence.reason)}`);
    } else {
      sections.push(
        `  first ${display(result.cadence.firstPublishedAt)} · last ${display(result.cadence.lastPublishedAt)} · median gap ${result.cadence.medianGapDays === null ? "unavailable" : `${result.cadence.medianGapDays}d`} · ${result.cadence.timestampRows} distinct timestamp(s)`,
      );
    }
    sections.push(`  ${result.cadence.note}`);

    sections.push("", "Audience (platform-reported insights; absences surfaced)");
    if (result.audience.state === "UNAVAILABLE") {
      sections.push(`  UNAVAILABLE — ${display(result.audience.reason)}`);
    } else {
      sections.push(
        table(
          ["metric", "period", "dimension", "value", "ends"],
          result.audience.latest.map((point) => [
            point.metric,
            point.period,
            display(point.dimensionValue ?? point.dimension),
            String(point.value),
            display(point.endTime === null ? null : point.endTime.slice(0, 10)),
          ]),
        ),
      );
      if (result.audience.latestAbsences.length > 0) {
        sections.push(
          "  Platform-reported absences (latest observation):",
          ...result.audience.latestAbsences.map(
            (absence) => `    ${absence.metric} ${absence.period}: ${absence.reason}`,
          ),
        );
      }
    }
    sections.push(`  ${result.audience.note}`);

    sections.push("", `Recent changes (recorded events, last ${result.changes.windowDays} days)`);
    if (result.changes.state === "UNAVAILABLE") {
      sections.push(`  UNAVAILABLE — ${display(result.changes.reason)}`);
    } else {
      const changeRow = (
        label: string,
        v: { count: number; latestAt: string | null } | null,
      ): string[] => [
        label,
        v === null ? "unavailable" : String(v.count),
        v === null || v.latestAt === null ? "unavailable" : v.latestAt.slice(0, 10),
      ];
      sections.push(
        table(
          ["kind", "recorded", "latest"],
          [
            changeRow("profile changes", result.changes.profileChanges),
            changeRow("post changes", result.changes.postChanges),
            changeRow("follow deltas", result.changes.followDeltas),
          ],
        ),
      );
    }
    sections.push(`  ${result.changes.note}`);

    sections.push("", "Claims (operator/agent-submitted findings — not observations)");
    sections.push(`  ${result.claims.statement}`);
    if (result.claims.since !== null) {
      sections.push(
        `  --since ${result.claims.since}: ${result.claims.omittedBefore} older claim row(s) omitted from this view (still stored; nothing deleted).`,
      );
    }
    renderClaimGroups(result.claims.groups, sections);
    if (result.claims.totals.retracted > 0) {
      const retractedRows = result.claims.retracted;
      sections.push(
        "",
        `Retracted (${result.claims.totals.retracted}, never deleted):`,
        table(
          ["value", "predicate", "retracted at", "reason"],
          retractedRows.map((claim) => [
            claim.value,
            claim.predicate,
            display(claim.retractedAt === null ? null : claim.retractedAt.slice(0, 10)),
            display(claim.retractionReason),
          ]),
        ),
      );
    }

    sections.push("", "Contradictions");
    if (result.contradictions.length === 0) {
      sections.push("  None: no predicate has conflicting active values.");
    } else {
      for (const contradiction of result.contradictions) {
        sections.push(`  ${contradiction.predicate}:`);
        for (const value of contradiction.values) {
          sections.push(`    "${value.value}"  <- ${value.sources.join(" ; ")}`);
        }
      }
    }

    sections.push("", "Leads (stored signal rows - not claims, not researched)");
    if (result.leads.state === "UNAVAILABLE") {
      sections.push(`  UNAVAILABLE - ${display(result.leads.reason)}`);
    } else {
      sections.push(
        table(
          ["account", "signals"],
          result.leads.items.map((lead) => [lead.username, lead.signals.join(" · ")]),
        ),
      );
      if (result.leads.syntheticItems.length > 0) {
        sections.push(
          "  Synthetic leads (fixture data — evidence about the fixture, never about a person):",
          table(
            ["account", "signals"],
            result.leads.syntheticItems.map((lead) => [lead.username, lead.signals.join(" · ")]),
          ),
        );
      }
    }
    sections.push(`  ${result.leads.note}`);

    sections.push("", "Connections (evidence-ranked; counts of stored rows, never affinity)");
    if (result.connections.state === "UNAVAILABLE") {
      sections.push(`  UNAVAILABLE - ${display(result.connections.reason)}`);
    } else {
      sections.push(
        table(
          ["account", "signals"],
          result.connections.ranks.map((rank) => [
            rank.username,
            `mentions x${rank.signals.mentions} · comments x${rank.signals.comments} · deltas x${rank.signals.deltas}`,
          ]),
        ),
      );
      if (result.connections.syntheticRanks.length > 0) {
        sections.push(
          "  Synthetic connections (fixture data — never evidence about a person):",
          table(
            ["account", "signals"],
            result.connections.syntheticRanks.map((rank) => [
              rank.username,
              `mentions x${rank.signals.mentions} · comments x${rank.signals.comments} · deltas x${rank.signals.deltas}`,
            ]),
          ),
        );
      }
      if (result.connections.truncated) {
        sections.push("  Note: more ranked accounts are stored than this list shows.");
      }
    }

    sections.push("", "Research runs (autonomous public-web acquisition; refusals and failures are findings)");
    if (result.researchRuns.state === "UNAVAILABLE") {
      sections.push(`  ${display(result.researchRuns.reason)}`);
      sections.push(`  ${result.researchRuns.note}`);
    } else {
      sections.push(
        table(
          ["run", "question", "focus", "status", "docs", "candidates", "stored/dup/refused", "started"],
          result.researchRuns.runs.map((run) => [
            run.id.slice(0, 8),
            run.question.length > 40 ? `${run.question.slice(0, 39)}…` : run.question,
            run.focusIntent,
            run.status,
            `${run.documentsFetched}/${run.documentsPlanned} fetched, ${run.documentsFailed} failed`,
            String(run.candidatesFound),
            `${run.claimsStored}/${run.claimsDuplicate}/${run.claimsRefused}`,
            run.startedAt.slice(0, 10),
          ]),
        ),
      );
      for (const run of result.researchRuns.runs) {
        if (run.searchUnavailableReason !== null) {
          sections.push(`  run ${run.id.slice(0, 8)} search UNAVAILABLE — ${run.searchUnavailableReason}`);
        }
      }
      sections.push(`  ${result.researchRuns.note}`);
    }

    sections.push(
      "",
      "Coverage (state is computed from stored rows; reasons are the platform's or the registry's)",
      table(
        ["capability", "state", "rows", "reason"],
        result.coverage.map((row) => [
          row.label,
          row.state,
          row.observedRows === null ? "no writer" : String(row.observedRows),
          row.reason === null ? "-" : row.reason.replace(/\s+/g, " ").slice(0, 90),
        ]),
      ),
    );

    sections.push("", "Notes:", ...result.notes.map((note) => `  · ${note}`));

    emit({
      json,
      meta: ctx.meta,
      data: result,
      human: format === "text" ? sections.join("\n") : researchMarkdown(result),
    });
    return 0;
  } finally {
    await ctx.close();
  }
}

export async function runPlan(args: ParsedArgs): Promise<number> {
  const json = isJson(args.flags);
  const target = args.positionals[0];
  if (target === undefined) {
    throw new UsageError("Usage: igtrack plan <target id|username> [--goal G]");
  }
  const ctx = await createContext();
  try {
    const result = await opPlan(ctx, { target, goal: flagString(args.flags, "goal") });
    const sections: string[] = [
      `Plan      @${result.target.username}  (${result.target.observationMode} · ${result.target.status})  goal ${result.goal}  computed ${result.computedAt}`,
      "",
      table(
        ["status", "step", "tool", "reason"],
        result.steps.map((step) => [
          step.status,
          step.id,
          step.tool,
          step.reason === null ? "-" : step.reason.replace(/\s+/g, " ").slice(0, 110),
        ]),
      ),
    ];
    if (result.nextAction === null) {
      sections.push("", "Next      nothing to run: every step is DONE or not applicable.");
    } else {
      sections.push(
        "",
        `Next      ${result.nextAction.tool} ${JSON.stringify(result.nextAction.params)}`,
        `          because ${result.nextAction.because}`,
      );
    }
    sections.push("", "Notes:", ...result.notes.map((note) => `  · ${note}`));
    emit({ json, meta: ctx.meta, data: result, human: sections.join("\n") });
    return 0;
  } finally {
    await ctx.close();
  }
}
